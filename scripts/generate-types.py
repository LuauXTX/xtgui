"""Flatten the public declaration template's explicit table inheritance.

Development-only source generation. Runtime constructors do not depend on Python.
Flat contextual tables avoid Luau's mutable intersection/overload inference traps;
subclasses override fields such as Table.columns with their actual public type.
"""
from pathlib import Path
import re
import shutil
import subprocess
ROOT=Path(__file__).resolve().parents[1]
source=(ROOT/'types/public.luau.in').read_text(encoding='utf8')
def properties(table):
    if not table.startswith('{') or not table.endswith('}'):raise ValueError('Inheritance base must be a table')
    result={};start=0;stack=[];quote=None;escaped=False;body=table[1:-1]
    for index,char in enumerate(body+','):
        if quote:
            if escaped:escaped=False
            elif char=='\\':escaped=True
            elif char==quote:quote=None
        elif char in '\"\'':quote=char
        elif char in '([{':stack.append(char)
        elif char in ')]}':stack.pop()
        elif char==',' and not stack:
            field=body[start:index].strip();start=index+1
            if field:
                key=re.match(r'(\w+)\s*:',field)
                if not key:raise ValueError('Expected named declaration field: '+field[:60])
                result[key[1]]=field
    return result
matches=list(re.finditer(r'^export type (\w+)[^\n]*?=',source,re.M))
ending=source.rindex('\nreturn {}');resolved={};output=[source[:matches[0].start()]]
for index,match in enumerate(matches):
    end=matches[index+1].start() if index+1<len(matches) else ending
    declaration=source[match.end():end].strip();inheritance=re.fullmatch(r'(\w+)\s*&\s*(\{[\s\S]*\})',declaration)
    if inheritance:
        fields=properties(resolved[inheritance[1]]);fields.update(properties(inheritance[2]))
        declaration='{\n'+''.join('    '+field+',\n' for field in fields.values())+'}'
    resolved[match[1]]=declaration;output.append(match[0]+' '+declaration+'\n\n')
destination=ROOT/'src/Types.luau'
destination.write_text('-- Generated by scripts/generate-types.py from types/public.luau.in.\n'+''.join(output)+'return {}\n',encoding='utf8',newline='\n')
formatter=shutil.which('stylua')
if formatter:subprocess.run([formatter,str(destination)],cwd=ROOT,check=True)
print('Generated flattened public contracts:',destination)
